#!/usr/bin/env python3
"""Generates ../tc_lib.c from tc_headers.txt (the text of the Turbo C library headers).
Run:  python3 gen_tc_lib.py   (from this folder)"""
import re, os
here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, 'tc_headers.txt')).read()
parts = re.split(r'^=== (\S+)\n', src, flags=re.M)
heads = []
for i in range(1, len(parts), 2):
    heads.append((parts[i], parts[i + 1].strip('\n') + '\n'))

def clit(text):
    out = []
    for line in text.split('\n')[:-1]:
        esc = line.replace('\\', '\\\\').replace('"', '\\"')
        out.append('    "%s\\n"' % esc)
    return '\n'.join(out)

o = []
o.append('/* GENERATED by tc_tools/gen_tc_lib.py from tc_tools/tc_headers.txt - do not edit by hand. */')
o.append('#include <ctype.h>\n#include <string.h>\n#include "tc_int.h"\n')
for idx, (name, text) in enumerate(heads):
    o.append('static const char H%d[] =\n%s;\n' % (idx, clit(text)))
o.append('static const struct { const char *name; const char *text; } kHeaders[] = {')
for idx, (name, text) in enumerate(heads):
    o.append('    {"%s", H%d},' % (name, idx))
o.append('    {NULL, NULL}\n};\n')
o.append(r'''
const char *tc_header_text(const char *name)
{
    int i;
    for (i = 0; kHeaders[i].name; i++)
        if (strcmp(kHeaders[i].name, name) == 0) return kHeaders[i].text;
    return NULL;
}

/* names of every function the Turbo C run-time library provides: scanned from the header texts */
#define LTAB 2048
static struct LEnt { struct LEnt *next; char *name; } **g_ltab;

static unsigned lhash(const char *s)
{
    unsigned h = 5381;
    while (*s) h = h * 33 + (unsigned char)*s++;
    return h % LTAB;
}

static void lib_add(const char *s, size_t n)
{
    char *nm = tc_strndup(s, n);
    unsigned h = lhash(nm);
    struct LEnt *e;
    for (e = g_ltab[h]; e; e = e->next) if (strcmp(e->name, nm) == 0) return;
    e = (struct LEnt *)tc_alloc(sizeof *e);
    e->name = nm;
    e->next = g_ltab[h];
    g_ltab[h] = e;
}

void tc_lib_init(void)
{
    int i;
    g_ltab = (struct LEnt **)tc_alloc(sizeof(struct LEnt *) * LTAB);
    for (i = 0; kHeaders[i].name; i++) {
        const char *p = kHeaders[i].text;
        while (*p) {
            const char *eol = strchr(p, '\n');
            const char *q = p;
            if (!eol) eol = p + strlen(p);
            if (*p != '#') {
                while (q < eol) {
                    if (isalpha((unsigned char)*q) || *q == '_') {
                        const char *s = q;
                        const char *e;
                        while (q < eol && (isalnum((unsigned char)*q) || *q == '_')) q++;
                        e = q;
                        while (q < eol && *q == ' ') q++;
                        if (q < eol && *q == '(' && (s == p || s[-1] != '*' || 1)) lib_add(s, (size_t)(e - s));
                    } else q++;
                }
            }
            p = *eol ? eol + 1 : eol;
        }
    }
}

int tc_lib_has_symbol(const char *name)
{
    struct LEnt *e;
    if (!g_ltab) return 0;
    for (e = g_ltab[lhash(name)]; e; e = e->next) if (strcmp(e->name, name) == 0) return 1;
    return 0;
}
''')
open(os.path.join(here, '..', 'tc_lib.c'), 'w').write('\n'.join(o))
print("headers:", len(heads))
